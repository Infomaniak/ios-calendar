import Foundation
import SwiftUI

public enum StartDay: String, CaseIterable, Sendable, SettingsOptionEnum {
    case monday
    case tuesday
    case wednesday
    case thursday
    case friday
    case saturday
    case sunday

    public var title: String {
        switch self {
        case .monday:
            return "Monday"
        case .tuesday:
            return "Tuesday"
        case .wednesday:
            return "Wednesday"
        case .thursday:
            return "Thursday"
        case .friday:
            return "Friday"
        case .saturday:
            return "Saturday"
        case .sunday:
            return "Sunday"
        }
    }

    public var image: Image? {
        nil
    }

    public var hint: String? {
        nil
    }
}
